import { afterEach, expect, it, vi } from 'vitest'
import { GhosttyRuntime } from '../runtime.js'

let runtime: GhosttyRuntime | undefined

afterEach(() => {
  runtime?.dispose()
  runtime = undefined
  vi.useRealTimers()
})

it('captures the pre-hold frame inside a write and keeps native reads live', async () => {
  runtime = await GhosttyRuntime.create()
  const terminal = runtime.createTerminal({ columns: 16, rows: 3 })
  const state = runtime.createRenderState(terminal)
  terminal.write('old')
  state.update()
  state.acknowledge()
  terminal.write(' frame\x1b[?2026h\r\x1b[2Kpartial')
  state.update()
  expect(state.readTextRows()[0]?.text.trimEnd()).toBe('old frame')
  expect(state.readCursor().viewport?.x).toBe(9)
  expect(terminal.readLines(0, 1)[0]?.text.trimEnd()).toBe('partial')
  state.acknowledge()
  terminal.write(' complete')
  state.update()
  expect(state.readTextRows()[0]?.text.trimEnd()).toBe('old frame')
  terminal.write('\x1b[?2026l')
  state.update()
  expect(state.readTextRows()[0]?.text.trimEnd()).toBe('partial complete')
})

it('captures consecutive holds without an intervening draw', async () => {
  runtime = await GhosttyRuntime.create()
  const terminal = runtime.createTerminal({ columns: 16, rows: 3 })
  const state = runtime.createRenderState(terminal)
  terminal.write('old\x1b[?2026h\rfirst\x1b[?2026l\x1b[?2026h\rsecond')
  state.update()
  expect(state.readTextRows()[0]?.text.trimEnd()).toBe('first')
  terminal.write('\x1b[?2026l')
  state.update()
  expect(state.readTextRows()[0]?.text.trimEnd()).toBe('second')
})

it('releases a stuck hold after one second even when it is repeatedly set', async () => {
  vi.useFakeTimers()
  runtime = await GhosttyRuntime.create()
  const terminal = runtime.createTerminal({ columns: 16, rows: 3 })
  const state = runtime.createRenderState(terminal)
  terminal.write('old\x1b[?2026h\rnew')
  state.update()
  vi.advanceTimersByTime(900)
  terminal.write('\x1b[?2026h')
  state.update()
  expect(state.readTextRows()[0]?.text.trimEnd()).toBe('old')
  vi.advanceTimersByTime(100)
  state.update()
  expect(state.readTextRows()[0]?.text.trimEnd()).toBe('new')
  terminal.write('\x1b[?2026h\rlater')
  state.update()
  expect(state.readTextRows()[0]?.text.trimEnd()).toBe('new')
  runtime.dispose()
  expect(vi.getTimerCount()).toBe(0)
})

it.each(['\x1bc', 'resize'])('releases the hold on %s', async (reset) => {
  runtime = await GhosttyRuntime.create()
  const terminal = runtime.createTerminal({ columns: 16, rows: 3 })
  const state = runtime.createRenderState(terminal)
  terminal.write('old\x1b[?2026h\rnew')
  state.update()
  expect(state.readTextRows()[0]?.text.trimEnd()).toBe('old')
  if (reset === 'resize') terminal.resize({ columns: 17 })
  else terminal.write(reset)
  terminal.write('\rreleased')
  state.update()
  expect(state.readTextRows()[0]?.text.trimEnd()).toBe('released')
})

it('defers render states created during a hold without exposing unfinished output', async () => {
  runtime = await GhosttyRuntime.create()
  const terminal = runtime.createTerminal({ columns: 16, rows: 3 })
  terminal.write('before\x1b[?2026h\rpartial')
  const state = runtime.createRenderState(terminal)
  state.update()
  expect(state.readCursor().visible).toBe(false)
  expect(state.readRows()).toEqual([])
  expect(state.readTextRows()).toEqual([])
  expect(state.snapshot().rows).toEqual([])
  terminal.write('\x1b[?2026l')
  state.update()
  expect(state.readTextRows()[0]?.text.trimEnd()).toBe('partial')
  expect(state.readCursor().viewport?.x).toBe(7)
})
